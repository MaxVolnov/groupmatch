/**
 * Кто свободен в конкретной получасовке теплокарты.
 *
 * ЗАЧЕМ. Теплокарта проектировалась под вопрос «когда свободны все» — по цвету
 * видно пересечение, и этого хватало. Репетиторам нужен другой вопрос: «кто
 * именно отметил этот слот», потому что они назначают не одну общую встречу, а
 * по одной с каждым. Из репорта: «мне нужно видеть, кто какой слот отметил
 * непосредственно в таблице, а не только в графе участники».
 *
 * Имена приходят с сервера в `HeatmapSlot.displayNames` и заполняются, только
 * когда у группы включена настройка «показывать участников»; иначе там `null`.
 * Решение о том, кому имена видны, принимается на бэкенде и здесь не
 * пересматривается.
 */

/**
 * Сколько имён показывать целиком.
 *
 * Восемь — это примерно три строки на ширине 375px для русских имён. Больше
 * начинает отжимать саму таблицу вниз, а панель со списком не должна
 * конкурировать за экран с тем, ради чего её открыли.
 *
 * Обрезаем с остатком, а не заводим прокрутку внутри панели: страница уже
 * прокручивается, и вложенная область прокрутки на тач-экране — известный
 * способ отобрать жест у страницы. Точный состав больших групп смотрят во
 * вкладке участников, здесь нужен ответ «кто из них», а не полный список.
 */
export const MAX_VISIBLE_NAMES = 8

export interface CellNames {
  /** Имена, которые показываем целиком. */
  visible: string[]
  /** Сколько не поместилось; 0 — поместились все. */
  hiddenCount: number
  /** Сколько всего отметилось — совпадает с `count` ячейки. */
  total: number
}

/**
 * Готовит список имён к показу.
 *
 * @returns `null`, если показывать нечего: в ячейке никого нет либо имена
 *          скрыты настройкой группы. Пустая панель хуже отсутствующей — она
 *          занимает место и заставляет гадать, что означает пустота.
 */
export function cellNames(
  names: readonly string[] | null | undefined,
  max: number = MAX_VISIBLE_NAMES,
): CellNames | null {
  if (!names) return null

  // Пустые строки отбрасываем: сервер подставляет вместо имени идентификатор,
  // если пользователь не нашёлся, но пустого имени быть не должно, и показывать
  // пустое место в списке незачем.
  const cleaned = names.map((n) => n.trim()).filter((n) => n.length > 0)
  if (cleaned.length === 0) return null

  if (max <= 0) return { visible: [], hiddenCount: cleaned.length, total: cleaned.length }

  return {
    visible: cleaned.slice(0, max),
    hiddenCount: Math.max(0, cleaned.length - max),
    total: cleaned.length,
  }
}
