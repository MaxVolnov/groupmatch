/**
 * Фирменные цвета. Значения обязаны совпадать с CSS-переменными в
 * src/shared/brand.css: там они для статических страниц (`var(--gm-*)`),
 * здесь — для SPA, который свёрстан на Tailwind-утилитах.
 *
 * Объявлены один раз и переиспользуются ниже под двумя именами — числовым
 * (шкала) и семантическим (алиасы), чтобы одно значение нельзя было
 * поправить в одном месте и забыть в другом.
 */
const BRAND = {
  bg: '#040929',        // основной фон
  surface: '#0C1540',
  border: '#1A2757',
  accent: '#055EC2',    // основной синий: кнопки, активные состояния
  accentHover: '#0867D0',
  light: '#5DB7F4',     // светло-голубой: ссылки и акцентные подписи на тёмном
  deep: '#143291',      // глубокий синий: hover кнопок, бейдж админа
  muted: '#9AA8C7',
}

/**
 * Шкала оттенков. SPA использует светлую и тёмную темы, поэтому одного
 * значения на роль не хватает: ссылка на белом фоне не может быть того же
 * цвета, что на тёмном. Шкала повторяет привычную разметку Tailwind
 * (50…950), так что светло-тёмные пары вида `text-gm-600 dark:text-gm-400`
 * читаются так же, как раньше читались indigo.
 *
 * Опорные точки — фирменные цвета, промежуточные получены интерполяцией:
 *   400 = #5DB7F4   ссылки на тёмном фоне
 *   600 = #055EC2   основные кнопки, ссылки на светлом фоне
 *   700 = #143291   hover/active кнопок, бейдж админа
 *   950 = #040929   фон приложения
 *
 * Контраст проверен: белый на 600 — 6.20:1, белый на 700 — 11.08:1,
 * 400 на 950 — 8.87:1, 600 на белом — 6.20:1. Все пары от AA и выше.
 */
const SCALE = {
  50: '#EFF8FE',
  100: '#DFF1FD',
  200: '#C1E4FB',
  300: '#96D0F8',
  400: BRAND.light,
  500: '#2D86D8',
  600: BRAND.accent,
  700: BRAND.deep,
  800: '#0D2165',
  900: '#081446',
  950: BRAND.bg,
}

/** @type {import('tailwindcss').Config} */
module.exports = {
  content: [
    './index.html',
    './promo.html',
    './legal.html',
    './about.html',
    './src/**/*.{ts,tsx}',
    './src/promo/**/*.{ts,js}',
    './src/legal/**/*.{ts,js}',
    './src/about/**/*.{ts,js}',
    './src/shared/**/*.{ts,js}',
  ],
  darkMode: 'class',
  theme: {
    extend: {
      colors: {
        gm: {
          ...SCALE,
          // Семантические алиасы — те же значения под именами из brand.css.
          bg: BRAND.bg,
          surface: BRAND.surface,
          border: BRAND.border,
          accent: BRAND.accent,
          'accent-hover': BRAND.accentHover,
          'accent-light': BRAND.light,
          'accent-deep': BRAND.deep,
          muted: BRAND.muted,
        },
      },
      backgroundImage: {
        /**
         * Фон экрана входа. Повторяет OG-превью: тёмно-синяя база с мягким
         * диагональным свечением в левом верхнем углу и по центру.
         *
         * Именно градиент, а не картинка: превью весит 105 КБ, а три
         * radial-gradient'а — около 300 байт в CSS и ничего не грузят.
         * Подход тот же, что у промо-лендинга, — фон описан CSS, не ассетом.
         */
        'gm-auth': [
          'radial-gradient(1200px 800px at 12% 8%, #143291 0%, transparent 60%)',
          'radial-gradient(900px 600px at 50% 40%, #0A0F58 0%, transparent 65%)',
          'radial-gradient(700px 500px at 85% 90%, #0D2165 0%, transparent 70%)',
          'linear-gradient(160deg, #040929 0%, #040929 100%)',
        ].join(','),
      },
    },
  },
  plugins: [],
}
