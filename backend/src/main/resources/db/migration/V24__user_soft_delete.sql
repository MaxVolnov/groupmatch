-- V24: мягкое удаление аккаунта.
--
-- Физически строку не удаляем никогда. Причины две.
--
-- Первая: у app_user висят каскады ON DELETE CASCADE почти отовсюду (V12),
-- и DELETE унёс бы вместе с человеком встречи, которые он создавал для
-- группы, — то есть данные других людей.
--
-- Вторая: отсрочка. Между «удалить» и «данных больше нет» есть 30 дней, в
-- которые аккаунт можно вернуть. Обезличивание по истечении срока делает
-- AccountAnonymizationJob: адрес заменяется, имя обезличивается, хеш пароля
-- затирается, слоты доступности удаляются, встречи остаются.
--
-- Два поля, а не одно с состоянием: deleted_at отвечает на «когда попросили
-- удалить», anonymized_at — на «когда данные фактически исчезли». Восстановить
-- можно только между этими двумя моментами, и по паре дат это видно прямо в
-- запросе, без вычислений.
ALTER TABLE app_user
    ADD COLUMN IF NOT EXISTS deleted_at    TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS anonymized_at TIMESTAMPTZ;

-- Частичный индекс: у подавляющего большинства строк deleted_at IS NULL, и
-- в индексе им делать нечего. Джоба обезличивания и фильтр «Удалённые» в
-- админке ходят ровно по непустым значениям.
CREATE INDEX IF NOT EXISTS idx_user_deleted_at
    ON app_user (deleted_at)
    WHERE deleted_at IS NOT NULL;

COMMENT ON COLUMN app_user.deleted_at IS
    'Момент запроса на удаление. Вход запрещён, аккаунт можно восстановить, пока anonymized_at пуст.';
COMMENT ON COLUMN app_user.anonymized_at IS
    'Момент обезличивания. После него восстановление невозможно: исходных данных больше нет.';
