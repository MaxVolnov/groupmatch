-- Индекс на subscription.yookassa_payment_id.
--
-- V17 завела колонку без индекса, а поиск по ней — основной путь обработки
-- вебхука ЮKassa: на каждое уведомление о платеже делается выборка по этому
-- значению. Пока подписок единицы, разница незаметна; когда их станет много,
-- вебхук начнёт упираться в последовательное сканирование таблицы, причём в
-- том самом месте, где мы обязаны ответить провайдеру быстро.
--
-- UNIQUE не ставим: колонка nullable (запись создаётся раньше, чем платёж
-- получает идентификатор), а в качестве защиты от дублей уже работает
-- Idempotence-Key на стороне ЮKassa.
CREATE INDEX IF NOT EXISTS idx_subscription_yookassa_payment_id
    ON subscription (yookassa_payment_id);
