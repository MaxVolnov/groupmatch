-- Повторяющиеся серии доступности.
--
-- Решение по архитектуре: серия разворачивается в обычные слоты при создании,
-- а не хранится правилом и разворачивается на чтение. Поэтому здесь нет ни
-- таблицы правил, ни RRULE — только метка «эти строки завели одним действием».
-- Теплокарта и подсчёт пересечений читают ту же таблицу тем же запросом и о
-- существовании серий не знают вовсе.
--
-- Цена решения известна и принята: перенести время у всей серии разом нельзя
-- (правила, которое можно было бы переписать, не существует), а серия «до
-- бесконечности» невозможна в принципе — есть потолок в 200 слотов.
--
-- NULL у одиночного слота — не «неизвестно», а «слота не в серии». Дефолта
-- нет намеренно: существующие строки одиночные и такими должны остаться.
ALTER TABLE availability ADD COLUMN series_id UUID;

-- Под единственный запрос, который по этой колонке ходит: удаление серии
-- целиком (DELETE /availability/{id}?scope=series). Без индекса это полное
-- сканирование таблицы всей группы ради нескольких строк.
CREATE INDEX idx_availability_series_id ON availability (series_id);

COMMENT ON COLUMN availability.series_id IS
    'Общий идентификатор слотов одной повторяющейся серии; NULL у одиночного слота';
