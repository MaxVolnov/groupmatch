package com.groupmatch.dto.admin;

/**
 * Фильтр списка пользователей в админке.
 *
 * Применяется на сервере, а не отсевом на клиенте: список постраничный, и
 * клиентский фильтр показывал бы «3 из 20» там, где всего 20 на странице из
 * тысячи, — то есть врал бы про количество.
 */
public enum AdminUserFilter {

    /** Все, включая гостей, тестовые и удалённые. */
    ALL,

    /** Живые люди: не гость, не тестовый домен, не удалён. */
    REAL,

    GUESTS,

    /** Аккаунты smoke-теста — по домену из {@code app.test-account-domain}. */
    TEST,

    /** С непустым {@code deleted_at}, включая уже обезличенные. */
    DELETED;

    /** Значение для запроса: JPQL сравнивает со строкой в нижнем регистре. */
    public String queryValue() {
        return name().toLowerCase();
    }
}
